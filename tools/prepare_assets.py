"""Convert bundled GIFs to timed JPEG frames for M5GFX. Requires Pillow.

Run from any directory: python demos/19-pokemon-nfc/tools/prepare_assets.py
All frames share a crop, so the sprite doesn't jump as its pose changes.
"""
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageSequence

ROOT = Path(__file__).resolve().parents[1]
BACKGROUND = (13, 22, 35)


def generate():
    lines = ['// Generated by tools/prepare_assets.py; do not edit.',
             '#pragma once', '#include <Arduino.h>',
             'struct PokemonFrame { const uint8_t* data; uint32_t size; uint16_t ms; };',
             'struct PokemonAnimation { const PokemonFrame* frames; uint16_t count; };']
    totals = []
    for name in ('bulbasaur', 'charmander', 'squirtle'):
        with Image.open(ROOT / 'assets' / f'{name}.gif') as gif:
            frames = [(f.convert('RGBA').copy(), max(20, f.info.get('duration', 100)))
                      for f in ImageSequence.Iterator(gif)]
        boxes = [im.getchannel('A').getbbox() for im, _ in frames]
        boxes = [b for b in boxes if b]
        box = (min(b[0] for b in boxes), min(b[1] for b in boxes),
               max(b[2] for b in boxes), max(b[3] for b in boxes))
        scale = min(120 / (box[2]-box[0]), 120 / (box[3]-box[1]))
        size = (round((box[2]-box[0])*scale), round((box[3]-box[1])*scale))
        descriptors = []
        total = 0
        for i, (im, duration) in enumerate(frames):
            im = im.crop(box).resize(size, Image.Resampling.NEAREST)
            canvas = Image.new('RGB', (160, 128), BACKGROUND)
            canvas.paste(im, ((160-size[0])//2, (128-size[1])//2), im)
            jpg = BytesIO()
            canvas.save(jpg, format='JPEG', quality=95, subsampling=0)
            data = jpg.getvalue()
            total += len(data)
            symbol = f'{name}_{i}'
            lines.append(f'const uint8_t {symbol}[] PROGMEM = {{')
            lines.extend(','.join(str(b) for b in data[j:j+32])+',' for j in range(0,len(data),32))
            lines.append('};')
            descriptors.append(f'    {{{symbol}, sizeof({symbol}), {duration}}},')
        lines.append(f'const PokemonFrame {name}_frames[] = {{')
        lines.extend(descriptors)
        lines.append('};')
        totals.append((name, len(frames), total))
    lines.append('const PokemonAnimation ANIMATIONS[] = {')
    for name, count, total in totals:
        lines.append(f'    {{{name}_frames, {count}}},')
        print(f'{name}: {count} frames, {total:,} bytes')
    lines.append('};')
    (ROOT / 'src/animations.h').write_text('\n'.join(lines)+'\n', encoding='utf-8')


if __name__ == '__main__':
    generate()
